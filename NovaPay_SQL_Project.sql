-- LAST MODULE --- CREATE A VIEW IN SQL SERVER

-- BUSINESS PROBLEM --- NOVAPAY ANALYTICS TEAM WANTS ONE CONSISTENT DATASET FOR REPORTING IN POWERBI, INSTEAD OF REWRITING JOINS 
-- AND CALCULATIONS EVERYTIME, WE WILL CREATE A SQL VIEW THAT COMBINES..
-- CUSTOMER INFORMATION, ACCOUNT DETAILS, BALANCES, TRANSACTION COUNTS AND AMOUNTS, SUCCESSFUL, FAILED AND PENDING TRANSACTION METRICS
-- CUSTOMER RANKINGS BY TRANSACTION ACTIVITY 


CREATE OR REPLACE VIEW vw_NovaPayAccountAnalytics AS
WITH TransactionSummary AS (
    SELECT
        AccountID,
        COUNT(*) AS TotalTransactions,
        SUM(CASE WHEN Status = 'Success' THEN 1 ELSE 0 END)
            AS SuccessfulTransactions,
        SUM(CASE WHEN Status = 'Failed' THEN 1 ELSE 0 END)
            AS FailedTransactions,
        SUM(CASE WHEN Status = 'Pending' THEN 1 ELSE 0 END)
            AS PendingTransactions,
        SUM(CASE
            WHEN Status = 'Success' THEN Amount
            ELSE 0
        END) AS TotalSuccessfulTransactionValue
    FROM Transactions
    GROUP BY AccountID
),
AccountAnalytics AS (
    SELECT
        c.CustomerID,
        c.FullName,
        c.City,
        a.AccountID,
        a.AccountType,
        a.Balance,
        COALESCE(ts.TotalTransactions, 0) AS TotalTransactions,
        COALESCE(ts.SuccessfulTransactions, 0)
            AS SuccessfulTransactions,
        COALESCE(ts.FailedTransactions, 0) AS FailedTransactions,
        COALESCE(ts.PendingTransactions, 0) AS PendingTransactions,
        COALESCE(ts.TotalSuccessfulTransactionValue, 0)
            AS TotalSuccessfulTransactionValue
    FROM Customers c
    INNER JOIN Accounts a
        ON c.CustomerID = a.CustomerID
    LEFT JOIN TransactionSummary ts
        ON a.AccountID = ts.AccountID
)
SELECT
    *,
    RANK() OVER (
        ORDER BY TotalSuccessfulTransactionValue DESC
    ) AS TransactionValueRank
FROM AccountAnalytics;

